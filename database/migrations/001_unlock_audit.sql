-- superuser as their object owner, even though the extension itself is owned
-- by icon_audit_owner. Reset to the privileged migration session so this
-- revoke also applies to those functions instead of producing ineffective
-- "no privileges could be revoked" warnings.
RESET ROLE;
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA audit FROM PUBLIC;
GRANT EXECUTE ON FUNCTION audit.digest(bytea, text) TO icon_audit_owner;
SET LOCAL ROLE icon_audit_owner;
REVOKE EXECUTE ON FUNCTION audit.begin_unlock_audit_attempt(uuid, text, text)
  FROM icon_audit_runtime, icon_dev;
REVOKE EXECUTE ON FUNCTION audit.finish_unlock_audit(uuid, audit.unlock_audit_outcome)
  FROM icon_audit_runtime, icon_dev;
REVOKE EXECUTE ON FUNCTION audit.record_unlock_decision(uuid, text, text, audit.unlock_audit_outcome, text, text)
  FROM icon_audit_runtime, icon_dev;
REVOKE EXECUTE ON FUNCTION audit.verify_unlock_audit_chain()
  FROM icon_audit_runtime, icon_dev;

GRANT USAGE ON SCHEMA audit TO icon_audit_runtime, icon_dev;
GRANT USAGE ON TYPE audit.unlock_audit_outcome TO icon_audit_runtime, icon_dev;
GRANT SELECT ON audit.unlock_audit_events TO icon_audit_runtime, icon_dev;
GRANT EXECUTE ON FUNCTION audit.begin_unlock_audit_attempt(uuid, text, text) TO icon_audit_runtime;
GRANT EXECUTE ON FUNCTION audit.finish_unlock_audit(uuid, audit.unlock_audit_outcome) TO icon_audit_runtime;
GRANT EXECUTE ON FUNCTION audit.record_unlock_decision(uuid, text, text, audit.unlock_audit_outcome, text, text)
  TO icon_audit_runtime;
GRANT EXECUTE ON FUNCTION audit.verify_unlock_audit_chain() TO icon_audit_runtime, icon_dev;

ALTER DEFAULT PRIVILEGES FOR ROLE icon_audit_owner IN SCHEMA audit REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE icon_audit_owner IN SCHEMA audit REVOKE ALL ON SEQUENCES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE icon_audit_owner IN SCHEMA audit REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

RESET ROLE;
COMMIT;

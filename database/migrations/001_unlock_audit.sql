\set ON_ERROR_STOP on

BEGIN;

CREATE SCHEMA IF NOT EXISTS audit AUTHORIZATION icon_audit_owner;
SET LOCAL ROLE icon_audit_owner;

REVOKE CREATE ON SCHEMA public FROM PUBLIC;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA audit;

DO $migration$
BEGIN
  IF NOT EXISTS (
    SELECT 1
      FROM pg_type AS type
      JOIN pg_namespace AS namespace ON namespace.oid = type.typnamespace
     WHERE namespace.nspname = 'audit'
       AND type.typname = 'unlock_audit_outcome'
  ) THEN
    CREATE TYPE audit.unlock_audit_outcome AS ENUM ('ATTEMPT', 'SUCCESS', 'FAILURE', 'DENIED', 'UNKNOWN');
  END IF;
END
$migration$;

CREATE TABLE IF NOT EXISTS audit.unlock_audit_events (
  event_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  correlation_id uuid NOT NULL,
  operator_subject text,
  target_user_id text,
  action text NOT NULL DEFAULT 'user:unlock',
  outcome audit.unlock_audit_outcome NOT NULL,
  code text NOT NULL,
  severity text NOT NULL,
  occurred_at timestamptz(6) NOT NULL DEFAULT clock_timestamp(),
  previous_event_hash bytea,
  event_hash bytea NOT NULL,
  CONSTRAINT unlock_audit_operator_subject_format CHECK (
    operator_subject IS NULL OR char_length(operator_subject) BETWEEN 1 AND 255
  ),
  CONSTRAINT unlock_audit_target_user_id_format CHECK (
    target_user_id IS NULL OR target_user_id ~ '^[A-Za-z0-9_-]{1,128}$'
  ),
  CONSTRAINT unlock_audit_action CHECK (action = 'user:unlock'),
  CONSTRAINT unlock_audit_code_format CHECK (code ~ '^[A-Z][A-Z0-9_]{0,63}$'),
  CONSTRAINT unlock_audit_severity CHECK (severity IN ('INFORMATION', 'ALERT')),
  CONSTRAINT unlock_audit_previous_hash_size CHECK (
    previous_event_hash IS NULL OR octet_length(previous_event_hash) = 32
  ),
  CONSTRAINT unlock_audit_event_hash_size CHECK (octet_length(event_hash) = 32)
);

COMMENT ON TABLE audit.unlock_audit_events IS
  'Append-only Débloquer audit events. Fixed columns deliberately exclude credentials, tokens, secrets, and upstream bodies.';
COMMENT ON COLUMN audit.unlock_audit_events.correlation_id IS
  'Idempotency and reconciliation key generated by the BFF for one unlock operation.';
COMMENT ON COLUMN audit.unlock_audit_events.event_hash IS
  'SHA-256 chain value over the prior hash and all security-relevant fields of this event.';

CREATE UNIQUE INDEX IF NOT EXISTS unlock_audit_one_attempt_per_operation
  ON audit.unlock_audit_events (correlation_id)
  WHERE outcome = 'ATTEMPT';

CREATE UNIQUE INDEX IF NOT EXISTS unlock_audit_one_terminal_per_operation
  ON audit.unlock_audit_events (correlation_id)
  WHERE outcome <> 'ATTEMPT';

CREATE INDEX IF NOT EXISTS unlock_audit_events_occurred_at
  ON audit.unlock_audit_events (occurred_at DESC, event_id DESC);

CREATE OR REPLACE FUNCTION audit.compute_unlock_event_hash(
  p_previous_event_hash bytea,
  p_correlation_id uuid,
  p_operator_subject text,
  p_target_user_id text,
  p_action text,
  p_outcome audit.unlock_audit_outcome,
  p_code text,
  p_severity text,
  p_occurred_at timestamptz
)
RETURNS bytea
LANGUAGE sql
IMMUTABLE
SET search_path = pg_catalog, audit
AS $function$
  SELECT audit.digest(
    convert_to(
      jsonb_build_array(
        encode(p_previous_event_hash, 'hex'),
        p_correlation_id::text,
        p_operator_subject,
        p_target_user_id,
        p_action,
        p_outcome::text,
        p_code,
        p_severity,
        to_char(p_occurred_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"')
      )::text,
      'UTF8'
    ),
    'sha256'
  )
$function$;

CREATE OR REPLACE FUNCTION audit.append_unlock_event_internal(
  p_correlation_id uuid,
  p_operator_subject text,
  p_target_user_id text,
  p_outcome audit.unlock_audit_outcome,
  p_code text,
  p_severity text
)
RETURNS bigint
LANGUAGE plpgsql
SET search_path = pg_catalog, audit
AS $function$
DECLARE
  v_previous_event_hash bytea;
  v_event_hash bytea;
  v_event_id bigint;
  v_occurred_at timestamptz(6) := clock_timestamp();
BEGIN
  PERFORM pg_advisory_xact_lock(122993337, 4747);

  SELECT event_hash
    INTO v_previous_event_hash
    FROM audit.unlock_audit_events
   ORDER BY event_id DESC
   LIMIT 1;

  v_event_hash := audit.compute_unlock_event_hash(
    v_previous_event_hash,
    p_correlation_id,
    p_operator_subject,
    p_target_user_id,
    'user:unlock',
    p_outcome,
    p_code,
    p_severity,
    v_occurred_at
  );

  INSERT INTO audit.unlock_audit_events (
    correlation_id,
    operator_subject,
    target_user_id,
    action,
    outcome,
    code,
    severity,
    occurred_at,
    previous_event_hash,
    event_hash
  )
  VALUES (
    p_correlation_id,
    p_operator_subject,
    p_target_user_id,
    'user:unlock',
    p_outcome,
    p_code,
    p_severity,
    v_occurred_at,
    v_previous_event_hash,
    v_event_hash
  )
  RETURNING event_id INTO v_event_id;

  RETURN v_event_id;
END
$function$;

CREATE OR REPLACE FUNCTION audit.begin_unlock_audit_attempt(
  p_correlation_id uuid,
  p_operator_subject text,
  p_target_user_id text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, audit
AS $function$
BEGIN
  PERFORM pg_advisory_xact_lock(122993337, 4747);

  IF p_operator_subject IS NULL OR p_target_user_id IS NULL THEN
    RAISE EXCEPTION 'Unlock ATTEMPT requires an operator and target' USING ERRCODE = '23514';
  END IF;

  IF EXISTS (SELECT 1 FROM audit.unlock_audit_events WHERE correlation_id = p_correlation_id) THEN
    RAISE EXCEPTION 'Audit correlation ID already exists' USING ERRCODE = '23505';
  END IF;

  RETURN audit.append_unlock_event_internal(
    p_correlation_id,
    p_operator_subject,
    p_target_user_id,
    'ATTEMPT',
    'USER_UNLOCK_ATTEMPT',
    'INFORMATION'
  );
END
$function$;

CREATE OR REPLACE FUNCTION audit.finish_unlock_audit(
  p_correlation_id uuid,
  p_outcome audit.unlock_audit_outcome
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, audit
AS $function$
DECLARE
  v_attempt audit.unlock_audit_events%ROWTYPE;
  v_code text;
  v_severity text;
BEGIN
  PERFORM pg_advisory_xact_lock(122993337, 4747);

  IF p_outcome NOT IN ('SUCCESS', 'FAILURE', 'UNKNOWN') THEN
    RAISE EXCEPTION 'Invalid terminal unlock outcome' USING ERRCODE = '23514';
  END IF;

  SELECT *
    INTO v_attempt
    FROM audit.unlock_audit_events
   WHERE correlation_id = p_correlation_id
     AND outcome = 'ATTEMPT';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Confirmed ATTEMPT is required before terminal audit' USING ERRCODE = '23514';
  END IF;

  IF EXISTS (
    SELECT 1
      FROM audit.unlock_audit_events
     WHERE correlation_id = p_correlation_id
       AND outcome <> 'ATTEMPT'
  ) THEN
    RAISE EXCEPTION 'Terminal audit event already exists' USING ERRCODE = '23505';
  END IF;

  v_code := CASE p_outcome
    WHEN 'SUCCESS' THEN 'USER_UNLOCKED'
    WHEN 'FAILURE' THEN 'USER_UNLOCK_FAILED'
    ELSE 'USER_UNLOCK_OUTCOME_UNKNOWN'
  END;
  v_severity := CASE WHEN p_outcome = 'UNKNOWN' THEN 'ALERT' ELSE 'INFORMATION' END;

  RETURN audit.append_unlock_event_internal(
    p_correlation_id,
    v_attempt.operator_subject,
    v_attempt.target_user_id,
    p_outcome,
    v_code,
    v_severity
  );
END
$function$;

CREATE OR REPLACE FUNCTION audit.record_unlock_decision(
  p_correlation_id uuid,
  p_operator_subject text,
  p_target_user_id text,
  p_outcome audit.unlock_audit_outcome,
  p_code text,
  p_severity text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, audit
AS $function$
BEGIN
  PERFORM pg_advisory_xact_lock(122993337, 4747);

  IF p_outcome NOT IN ('DENIED', 'FAILURE') THEN
    RAISE EXCEPTION 'Only pre-dispatch DENIED or FAILURE events may use this function' USING ERRCODE = '23514';
  END IF;

  IF EXISTS (SELECT 1 FROM audit.unlock_audit_events WHERE correlation_id = p_correlation_id) THEN
    RAISE EXCEPTION 'Audit correlation ID already exists' USING ERRCODE = '23505';
  END IF;

  RETURN audit.append_unlock_event_internal(
    p_correlation_id,
    p_operator_subject,
    p_target_user_id,
    p_outcome,
    p_code,
    p_severity
  );
END
$function$;

CREATE OR REPLACE FUNCTION audit.reject_unlock_audit_mutation()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, audit
AS $function$
BEGIN
  RAISE EXCEPTION 'Unlock audit events are append-only' USING ERRCODE = '55000';
END
$function$;

DROP TRIGGER IF EXISTS unlock_audit_no_update_or_delete ON audit.unlock_audit_events;
CREATE TRIGGER unlock_audit_no_update_or_delete
  BEFORE UPDATE OR DELETE ON audit.unlock_audit_events
  FOR EACH ROW EXECUTE FUNCTION audit.reject_unlock_audit_mutation();

DROP TRIGGER IF EXISTS unlock_audit_no_truncate ON audit.unlock_audit_events;
CREATE TRIGGER unlock_audit_no_truncate
  BEFORE TRUNCATE ON audit.unlock_audit_events
  FOR EACH STATEMENT EXECUTE FUNCTION audit.reject_unlock_audit_mutation();

CREATE OR REPLACE FUNCTION audit.verify_unlock_audit_chain()
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, audit
AS $function$
DECLARE
  v_event audit.unlock_audit_events%ROWTYPE;
  v_expected_hash bytea;
  v_previous_event_hash bytea;
BEGIN
  FOR v_event IN SELECT * FROM audit.unlock_audit_events ORDER BY event_id LOOP
    IF v_event.previous_event_hash IS DISTINCT FROM v_previous_event_hash THEN
      RETURN false;
    END IF;

    v_expected_hash := audit.compute_unlock_event_hash(
      v_previous_event_hash,
      v_event.correlation_id,
      v_event.operator_subject,
      v_event.target_user_id,
      v_event.action,
      v_event.outcome,
      v_event.code,
      v_event.severity,
      v_event.occurred_at
    );

    IF v_event.event_hash IS DISTINCT FROM v_expected_hash THEN
      RETURN false;
    END IF;

    v_previous_event_hash := v_event.event_hash;
  END LOOP;

  RETURN true;
END
$function$;

REVOKE ALL ON SCHEMA audit FROM PUBLIC;
REVOKE ALL ON TYPE audit.unlock_audit_outcome FROM PUBLIC;
REVOKE ALL ON audit.unlock_audit_events FROM PUBLIC, icon_audit_runtime, icon_dev;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA audit FROM PUBLIC, icon_audit_runtime, icon_dev;
